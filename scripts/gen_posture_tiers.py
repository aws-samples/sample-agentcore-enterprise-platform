"""Generate docs/POSTURE_TIERS.md: security and observability keys per posture tier.

Run ``python scripts/gen_posture_tiers.py`` to regenerate the page, or add
``--check`` to exit non-zero when the committed page is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from infra_utils.platform_config import (
    POSTURE_DESCRIPTIONS,
    POSTURES,
    SHORTCUTS,
)

OUTPUT = REPO_ROOT / "docs" / "POSTURE_TIERS.md"
REGENERATE_COMMAND = "python scripts/gen_posture_tiers.py"

# Posture tier -> preset file. Repoint these when layered posture presets land.
TIER_PRESETS = (
    ("workshop", "presets/greenfield.yaml"),
    ("secure", "presets/security-focused.yaml"),
    ("production", "presets/production.yaml"),
)

# Security and observability sections (dotted prefixes) shown in the table.
SECTION_PREFIXES = (
    "agents.allowed_models",
    "agents.memory",
    "audit",
    "cedar",
    "cloudtrail",
    "deployment.mode",
    "egress",
    "encryption",
    "gateway",
    "guardrails",
    "identity",
    "idp",
    "kms",
    "lifecycle",
    "networking",
    "observability",
    "policy",
    "removal",
    "retention",
    "security",
)

# Any key segment containing one of these words is security-relevant wherever it lives.
KEYWORDS = (
    "alarm",
    "allowed_models",
    "cedar",
    "cloudtrail",
    "egress",
    "encrypt",
    "guardrail",
    "kms",
    "removal",
    "retention",
    "traceability",
    "tracing",
)

# Never shown: account, region, framework and use-case selection.
EXCLUDED_PREFIXES = (
    "accounts",
    "agent_pattern",
    "agents.framework",
    "agents.pattern",
    "framework",
    "region",
    "use_cases",
    "usecases",
)

ABSENT = "\u2014 (default)"

BANNER = (
    "<!-- Generated by scripts/gen_posture_tiers.py. Do not edit by hand; "
    f"run `{REGENERATE_COMMAND}` to regenerate. -->"
)


def _matches(key: str, prefixes: tuple[str, ...]) -> bool:
    return any(key == p or key.startswith(p + ".") for p in prefixes)


def is_relevant(key: str) -> bool:
    """Return True when a dotted key belongs in the posture table."""
    if _matches(key, EXCLUDED_PREFIXES):
        return False
    if _matches(key, SECTION_PREFIXES):
        return True
    segments = key.lower().split(".")
    return any(word in segment for segment in segments for word in KEYWORDS)


def flatten(data: object, prefix: str = "") -> dict[str, object]:
    """Flatten nested mappings into dotted leaf keys."""
    out: dict[str, object] = {}
    if not isinstance(data, dict):
        return out
    for name, value in data.items():
        key = f"{prefix}.{name}" if prefix else str(name)
        if isinstance(value, dict):
            # An empty mapping (`security: {}`) sets nothing: its keys keep their defaults.
            out.update(flatten(value, key))
        else:
            out[key] = value
    return out


def load_preset(relative_path: str) -> dict[str, object]:
    path = REPO_ROOT / relative_path
    with path.open(encoding="utf-8") as handle:
        return flatten(yaml.safe_load(handle) or {})


def load_tiers() -> dict[str, dict[str, object]]:
    """Return tier -> filtered flat preset keys."""
    tiers = {}
    for tier, relative_path in TIER_PRESETS:
        flat = load_preset(relative_path)
        tiers[tier] = {k: v for k, v in flat.items() if is_relevant(k)}
    return tiers


def _scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if value == "":
        return '""'
    if isinstance(value, dict):
        if not value:
            return "{}"
        return yaml.safe_dump(value, default_flow_style=True, sort_keys=True).strip()
    return str(value)


def format_value(value: object) -> str:
    if isinstance(value, list):
        text = "[" + ", ".join(_scalar(item) for item in value) + "]"
    else:
        text = _scalar(value)
    return "`" + text.replace("|", "\\|") + "`"


def load_postures() -> dict[str, dict[str, object]]:
    """Return posture layer -> filtered flat keys, straight from POSTURES."""
    return {
        name: {k: v for k, v in flatten(layer).items() if is_relevant(k)}
        for name, layer in POSTURES.items()
    }


def tier_postures() -> list[str]:
    """One sentence fragment per tier: its posture layer and overlay keys."""
    out = []
    for tier, relative_path in TIER_PRESETS:
        shortcut = SHORTCUTS[Path(relative_path).stem]
        overlay = sorted(
            k for k in flatten(shortcut.get("overlay", {})) if is_relevant(k)
        )
        text = f"**{tier}** uses posture `{shortcut['posture']}`"
        if overlay:
            text += " plus a shortcut overlay that sets " + ", ".join(
                f"`{k}`" for k in overlay
            )
        out.append(text)
    return out


def _table_lines(names: list[str], tiers: dict[str, dict[str, object]]) -> list[str]:
    lines = [
        "| key | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    keys = sorted({key for tier in names for key in tiers.get(tier, {})})
    for key in keys:
        cells = [
            format_value(tiers[tier][key]) if key in tiers.get(tier, {}) else ABSENT
            for tier in names
        ]
        label = f"`{key}`"
        if len(set(cells)) > 1:
            label = f"**{label}**"
            cells = [f"**{cell}**" for cell in cells]
        lines.append("| " + " | ".join([label, *cells]) + " |")
    return lines


def render(tiers: dict[str, dict[str, object]] | None = None) -> str:
    """Render the posture tiers page as Markdown."""
    if tiers is None:
        tiers = load_tiers()
    names = [tier for tier, _ in TIER_PRESETS]
    mapping = ", ".join(f"**{tier}** is `{path}`" for tier, path in TIER_PRESETS)
    lines = [
        BANNER,
        "",
        "# Posture tiers",
        "",
        "Each posture tier maps to one preset: "
        + mapping
        + ". The table lists every security and observability key the presets set, with "
        "the raw preset value for each tier. A key a preset does not set is shown as "
        f"`{ABSENT}`: the platform default applies (see [platform.yaml reference]"
        "(PLATFORM_YAML.md)). Rows in bold differ between tiers.",
        "",
        *_table_lines(names, tiers),
        "",
        "## Posture layers",
        "",
        (
            "`deploy.sh design` composes a design from a journey, a topology and "
            "one of these posture layers (`POSTURES` in "
            "`infra_utils/platform_config.py`):"
        ),
        "",
    ]
    lines += [f"- **`{name}`**: {POSTURE_DESCRIPTIONS[name]}" for name in POSTURES]
    lines += [
        "",
        "The tiers above are shortcuts built on these layers: "
        + "; ".join(tier_postures())
        + ".",
        "",
        (
            "The table lists the security and observability keys each posture "
            "layer sets on its own, before any shortcut overlay. Rows in bold "
            "differ between layers."
        ),
        "",
        *_table_lines(list(POSTURES), load_postures()),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if docs/POSTURE_TIERS.md is stale"
    )
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run `{REGENERATE_COMMAND}`",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
