class SoftwareFactoryDataStack(cdk.Stack):
    def __init__(self, scope: Construct, id: str, **kwargs):
        super().__init__(scope, id, **kwargs)
        self.runs = dynamodb.TableV2(
            self,
            "Runs",
            table_name="software-factory-runs",
            partition_key=dynamodb.Attribute(
                name="pk", type=dynamodb.AttributeType.STRING
            ),
            sort_key=dynamodb.Attribute(name="sk", type=dynamodb.AttributeType.STRING),
            billing=dynamodb.Billing.on_demand(),
            point_in_time_recovery_specification=dynamodb.PointInTimeRecoverySpecification(
                point_in_time_recovery_enabled=True
            ),
            removal_policy=cdk.RemovalPolicy.RETAIN,
        )
        self.dedupe = dynamodb.TableV2(
            self,
            "Dedupe",
            table_name="software-factory-dedupe",
            partition_key=dynamodb.Attribute(
                name="delivery_id", type=dynamodb.AttributeType.STRING
            ),
            billing=dynamodb.Billing.on_demand(),
            time_to_live_attribute="expires_at",
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )
        # PM consult conversations: grounding + turns per conversation_id, expired after 7 days.
        self.conversations = dynamodb.TableV2(
            self,
            "Conversations",
            table_name="software-factory-conversations",
            partition_key=dynamodb.Attribute(
                name="conversation_id", type=dynamodb.AttributeType.STRING
            ),
            sort_key=dynamodb.Attribute(name="sk", type=dynamodb.AttributeType.STRING),
            billing=dynamodb.Billing.on_demand(),
            time_to_live_attribute="expires_at",
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )
        # Generated by Secrets Manager at deploy time; never in the template or a log.
        self.webhook_secret = sm.Secret(
            self,
            "WebhookSecret",
            secret_name="software-factory/github-webhook-secret",
            description="GitHub webhook HMAC secret for the software factory ingress",
            generate_secret_string=sm.SecretStringGenerator(
                password_length=64, exclude_punctuation=True
            ),
        )
        # Not a secret; the ingress reads it so it never needs the App secret. 'none' = accept any installation.
        self.installation_id = ssm.StringParameter(
            self,
            "InstallationId",
            parameter_name="/software-factory/github-installation-id",
            string_value=self.node.try_get_context("installation_id") or "none",
            description="GitHub App installation id the webhook ingress accepts",
        )
        # Empty placeholder until the user creates the GitHub App; the agent runs dry-run while empty.
        self.github_app = sm.Secret(
            self,
            "GitHubApp",
            secret_name="software-factory/github-app",
            description="GitHub App {app_id, installation_id, private_key_pem}; '{}' = not configured (dry run)",
            secret_string_value=cdk.SecretValue.unsafe_plain_text("{}"),
        )


class SoftwareFactoryStack(cdk.Stack):
    def __init__(
        self,
        scope: Construct,
        id: str,
        *,
        data: SoftwareFactoryDataStack,
        coordinator_role_name: str,
        **kwargs,
    ):
        super().__init__(scope, id, **kwargs)
        self.log_key = self._log_key()
        runtime_arn = self._runtime(data)
        api = self._ingress(data, runtime_arn)
        self._cost_alarms(self._budget())
        self._readonly_role(data, coordinator_role_name)
        cdk.CfnOutput(self, "WebhookUrl", value=f"{api.api_endpoint}/github")
        cdk.CfnOutput(self, "RuntimeArn", value=runtime_arn)

    # --- logs ----------------------------------------------------------------
    def _log_key(self) -> kms.Key:
        key = kms.Key(
            self,
            "LogsKey",
            alias="alias/software-factory-logs",
            description="Encrypts the software factory's CloudWatch log groups",
            enable_key_rotation=True,
        )
        # CloudWatch Logs uses the key only for this stack's own log groups.
        key.add_to_resource_policy(
            iam.PolicyStatement(
                principals=[iam.ServicePrincipal(f"logs.{self.region}.amazonaws.com")],
                actions=[
                    "kms:Encrypt*",
                    "kms:Decrypt*",
                    "kms:ReEncrypt*",
                    "kms:GenerateDataKey*",
                    "kms:Describe*",
                ],
                resources=["*"],  # in a key policy "*" means this key
                conditions={
                    "ArnLike": {
                        "kms:EncryptionContext:aws:logs:arn": [
                            f"arn:aws:logs:{self.region}:{self.account}:log-group:{prefix}*"
                            for prefix in LOG_PREFIXES
                        ]
                    }
                },
            )
        )
        return key

    def _log_group(self, cid: str, name: str) -> logs.LogGroup:
        return logs.LogGroup(
            self,
            cid,
            log_group_name=name,
            retention=LOG_RETENTION,
            encryption_key=self.log_key,
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )

    def _runtime_log_settings(self, runtime_id: str) -> None:
        """AgentCore creates the runtime's log group itself, so set retention and the key on it afterwards."""
        name = f"/aws/bedrock-agentcore/runtimes/{runtime_id}-DEFAULT"
        arn = f"arn:aws:logs:{self.region}:{self.account}:log-group:{name}"
        policy = cr.AwsCustomResourcePolicy.from_statements(
            [
                iam.PolicyStatement(
                    actions=[
                        "logs:CreateLogGroup",
                        "logs:PutRetentionPolicy",
                        "logs:AssociateKmsKey",
                    ],
                    resources=[arn, f"{arn}:*"],
                )
            ]
        )
        fn_logs = self._log_group(
            "LogSettingsFnLogs", "/aws/lambda/software-factory-log-settings"
        )
        calls = [
            (
                "RuntimeLogGroup",
                "createLogGroup",
                {"logGroupName": name},
                "ResourceAlreadyExistsException",
            ),
            (
                "RuntimeLogRetention",
                "putRetentionPolicy",
                {"logGroupName": name, "retentionInDays": 30},
                None,
            ),
            (
                "RuntimeLogKey",
                "associateKmsKey",
                {"logGroupName": name, "kmsKeyId": self.log_key.key_arn},
                None,
            ),
        ]
        previous = None
        for cid, action, params, ignore in calls:
            call = cr.AwsSdkCall(
                service="CloudWatchLogs",
                action=action,
                parameters=params,
                physical_resource_id=cr.PhysicalResourceId.of(f"{name}:{action}"),
                ignore_error_codes_matching=ignore,
            )
            res = cr.AwsCustomResource(
                self,
                cid,
                on_create=call,
                on_update=call,
                policy=policy,
                log_group=fn_logs,
                install_latest_aws_sdk=False,
            )
            if previous:
                res.node.add_dependency(previous)
            previous = res

    # --- runtime -----------------------------------------------------------
    def _runtime(self, data: SoftwareFactoryDataStack) -> str:
        repo = ecr.Repository(
            self,
            "Ecr",
            repository_name="software-factory",
            image_scan_on_push=True,
            removal_policy=cdk.RemovalPolicy.DESTROY,
            empty_on_delete=True,
            lifecycle_rules=[ecr.LifecycleRule(max_image_count=10)],
        )
        # Build context = repo root filtered to the image's inputs (git-style patterns).
        source = s3_assets.Asset(
            self,
            "ImageSource",
            path=REPO_ROOT,
            ignore_mode=cdk.IgnoreMode.GIT,
            exclude=[
                "/*",
                "!/requirements.txt",
                "!/factory/",
                "/factory/*",
                "!/factory/Dockerfile",
                "!/factory/agent-code/",
                "__pycache__/",
                ".pytest_cache/",
                ".ruff_cache/",
            ],
        )
        tag = source.asset_hash[:16]
        build = codebuild.Project(
            self,
            "ImageBuild",
            project_name="software-factory-image-build",
            environment=codebuild.BuildEnvironment(
                build_image=codebuild.LinuxArmBuildImage.AMAZON_LINUX_2_STANDARD_3_0,
                privileged=True,
                compute_type=codebuild.ComputeType.SMALL,
            ),
            timeout=cdk.Duration.minutes(30),
            logging=codebuild.LoggingOptions(
                cloud_watch=codebuild.CloudWatchLoggingOptions(
                    log_group=self._log_group(
                        "ImageBuildLogs",
                        "/aws/codebuild/software-factory-image-build-logs",
                    )
                )
            ),
            build_spec=codebuild.BuildSpec.from_object(
                {
                    "version": "0.2",
                    "phases": {
                        "pre_build": {
                            "commands": [
                                (
                                    "aws ecr get-login-password --region $AWS_DEFAULT_REGION | docker login --username AWS "
                                    "--password-stdin $ACCOUNT_ID.dkr.ecr.$AWS_DEFAULT_REGION.amazonaws.com"
                                ),
                                "aws s3 cp $SOURCE_S3_URI source.zip && mkdir -p source && unzip -q -o source.zip -d source/",
                            ]
                        },
                        "build": {
                            "commands": [
                                "cd source && docker build --platform linux/arm64 -f factory/Dockerfile -t $REPO_URI:$IMAGE_TAG .",
                            ]
                        },
                        "post_build": {
                            "commands": ["docker push $REPO_URI:$IMAGE_TAG"]
                        },
                    },
                }
            ),
        )
        repo.grant_push(build)
        source.grant_read(build)
        trigger = _lambda.Function(
            self,
            "ImageBuildTrigger",
            runtime=_lambda.Runtime.PYTHON_3_13,
            handler="build_trigger_lambda.handler",
            code=_lambda.Code.from_asset(os.path.join(REPO_ROOT, "infra_utils")),
            timeout=cdk.Duration.minutes(15),
            memory_size=256,
            log_group=self._log_group(
                "ImageBuildTriggerLogs",
                "/aws/lambda/software-factory-image-build-trigger",
            ),
        )
        trigger.add_to_role_policy(
            iam.PolicyStatement(
                actions=["codebuild:StartBuild", "codebuild:BatchGetBuilds"],
                resources=[build.project_arn],
            )
        )
        built = cdk.CustomResource(
            self,
            "ImageBuildRun",
            service_token=trigger.function_arn,
            properties={
                "ProjectName": build.project_name,
                "SourceHash": tag,  # a new hash = a new build
                "EnvironmentOverrides": [
                    {
                        "name": "SOURCE_S3_URI",
                        "value": source.s3_object_url,
                        "type": "PLAINTEXT",
                    },
                    {"name": "IMAGE_TAG", "value": tag, "type": "PLAINTEXT"},
                    {
                        "name": "REPO_URI",
                        "value": repo.repository_uri,
                        "type": "PLAINTEXT",
                    },
                    {"name": "ACCOUNT_ID", "value": self.account, "type": "PLAINTEXT"},
                ],
            },
        )

        role = iam.Role(
            self,
            "RuntimeRole",
            role_name="software-factory-runtime",
            assumed_by=iam.ServicePrincipal(
                "bedrock-agentcore.amazonaws.com",
                conditions={
                    "StringEquals": {"aws:SourceAccount": self.account},
                    "ArnLike": {
                        "aws:SourceArn": f"arn:aws:bedrock-agentcore:{self.region}:{self.account}:*"
                    },
                },
            ),
        )
        for stmt in [
            iam.PolicyStatement(
                sid="EcrPull",
                actions=["ecr:BatchGetImage", "ecr:GetDownloadUrlForLayer"],
                resources=[repo.repository_arn],
            ),
            # Account-level token; IAM accepts only "*".
            iam.PolicyStatement(
                sid="EcrAuth", actions=["ecr:GetAuthorizationToken"], resources=["*"]
            ),
            iam.PolicyStatement(
                sid="Logs",
                actions=[
                    "logs:CreateLogGroup",
                    "logs:CreateLogStream",
                    "logs:PutLogEvents",
                    "logs:DescribeLogStreams",
                ],
                resources=[
                    f"arn:aws:logs:{self.region}:{self.account}:log-group:/aws/bedrock-agentcore/runtimes/software_factory*"
                ],
            ),
            # These accept no resource ARN; the namespace condition scopes PutMetricData.
            iam.PolicyStatement(
                sid="XRay",
                actions=["xray:PutTraceSegments", "xray:PutTelemetryRecords"],
                resources=["*"],
            ),
            iam.PolicyStatement(
                sid="Metrics",
                actions=["cloudwatch:PutMetricData"],
                resources=["*"],
                conditions={
                    "StringEquals": {
                        "cloudwatch:namespace": [METRIC_NAMESPACE, "bedrock-agentcore"]
                    }
                },
            ),
            iam.PolicyStatement(
                sid="Models",
                actions=[
                    "bedrock:InvokeModel",
                    "bedrock:InvokeModelWithResponseStream",
                ],
                resources=allowed_model_resources(ALLOWED_MODELS),
            ),
            iam.PolicyStatement(
                sid="RunsTable",
                actions=["dynamodb:PutItem", "dynamodb:UpdateItem", "dynamodb:Query"],
                resources=[data.runs.table_arn],
            ),
            iam.PolicyStatement(
                sid="Conversations",
                actions=["dynamodb:Query", "dynamodb:PutItem"],
                resources=[data.conversations.table_arn],
            ),
        ]:
            role.add_to_policy(stmt)
        data.github_app.grant_read(role)

        runtime = agentcore.CfnRuntime(
            self,
            "Runtime",
            agent_runtime_name="software_factory",
            role_arn=role.role_arn,
            description="Software factory agents; role chosen per invocation (ci_fixer)",
            agent_runtime_artifact={
                "containerConfiguration": {
                    "containerUri": f"{repo.repository_uri}:{tag}"
                }
            },
            network_configuration=build_network_config("PUBLIC", None, None),
            protocol_configuration="HTTP",
            environment_variables={
                "FACTORY_RUNS_TABLE": data.runs.table_name,
                "FACTORY_GITHUB_APP_SECRET": data.github_app.secret_name,  # a name, not a value
                "FACTORY_REPO": GITHUB_REPO,
                # PM issue writes (open, label, comment, close): off = the run lists what it would do.
                "FACTORY_PM_PUBLISH": self.node.try_get_context("factory_pm_publish")
                or "false",
                "FACTORY_CONVERSATIONS_TABLE": data.conversations.table_name,
                # Developer PRs: off until the user says; while off, branches stay in the runtime.
                "FACTORY_DEV_PUBLISH": self.node.try_get_context("factory_dev_publish")
                or "false",
                # Off until the user approves GitHub writes; while off, runs record the would-be PR.
                "FACTORY_PUBLISH": self.node.try_get_context("factory_publish")
                or "false",
                # Posting reviews to GitHub has its own switch; off = reviews go to the runs table only.
                "FACTORY_REVIEW_PUBLISH": self.node.try_get_context(
                    "factory_review_publish"
                )
                or "false",
            },
        )
        runtime.node.add_dependency(built, role)
        self._runtime_log_settings(runtime.attr_agent_runtime_id)
        return runtime.attr_agent_runtime_arn

    # --- ingress -----------------------------------------------------------
    def _ingress(
        self, data: SoftwareFactoryDataStack, runtime_arn: str
    ) -> apigw.HttpApi:
        dlq = sqs.Queue(
            self,
            "Dlq",
            queue_name="software-factory-events-dlq.fifo",
            fifo=True,
            encryption=sqs.QueueEncryption.SQS_MANAGED,
            retention_period=cdk.Duration.days(14),
            enforce_ssl=True,
        )
        queue = sqs.Queue(
            self,
            "Events",
            queue_name="software-factory-events.fifo",
            fifo=True,
            encryption=sqs.QueueEncryption.SQS_MANAGED,
            enforce_ssl=True,
            visibility_timeout=cdk.Duration.seconds(180),
            dead_letter_queue=sqs.DeadLetterQueue(queue=dlq, max_receive_count=3),
            # EventBridge rule targets cannot set a deduplication id; the ingress still sets its own.
            content_based_deduplication=True,
        )
        code = _lambda.Code.from_asset(os.path.join(HERE, "lambdas"))

        ingress = _lambda.Function(
            self,
            "Ingress",
            function_name="software-factory-ingress",
            runtime=_lambda.Runtime.PYTHON_3_13,
            handler="ingress.handler",
            code=code,
            timeout=cdk.Duration.seconds(10),
            memory_size=256,
            reserved_concurrent_executions=5,
            log_group=self._log_group(
                "IngressLogs", "/aws/lambda/software-factory-ingress"
            ),
            environment={
                "SECRET_ARN": data.webhook_secret.secret_arn,
                "INSTALLATION_PARAM": data.installation_id.parameter_name,
                "DEDUPE_TABLE": data.dedupe.table_name,
                "QUEUE_URL": queue.queue_url,
                "REPO": GITHUB_REPO,
            },
        )
        data.webhook_secret.grant_read(ingress)
        data.installation_id.grant_read(ingress)
        ingress.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:PutItem", "dynamodb:DeleteItem"],
                resources=[data.dedupe.table_arn],
            )
        )
        queue.grant_send_messages(ingress)

        dispatcher = _lambda.Function(
            self,
            "Dispatcher",
            function_name="software-factory-dispatcher",
            runtime=_lambda.Runtime.PYTHON_3_13,
            handler="dispatcher.handler",
            code=code,
            timeout=cdk.Duration.seconds(60),
            memory_size=256,
            environment={
                "RUNTIME_ARN": runtime_arn,
                "DLQ_URL": dlq.queue_url,
                # Hard stop: above this day's summed RunCostUSD, new runs are parked in the DLQ until 00:00 UTC.
                "DAILY_COST_STOP_USD": "10",
            },
            log_group=self._log_group(
                "DispatcherLogs", "/aws/lambda/software-factory-dispatcher"
            ),
        )
        dispatcher.add_to_role_policy(
            iam.PolicyStatement(
                actions=["bedrock-agentcore:InvokeAgentRuntime"],
                resources=[runtime_arn, f"{runtime_arn}/runtime-endpoint/*"],
            )
        )
        dlq.grant_send_messages(dispatcher)
        # GetMetricData accepts no resource ARN.
        dispatcher.add_to_role_policy(
            iam.PolicyStatement(actions=["cloudwatch:GetMetricData"], resources=["*"])
        )
        dispatcher.add_event_source(
            sources.SqsEventSource(
                queue,
                batch_size=1,
                report_batch_item_failures=True,
                # -c factory_dispatch=false pauses webhook-driven runs; events wait in the queue (4 days).
                enabled=(self.node.try_get_context("factory_dispatch") or "true")
                == "true",
            )
        )

        # 00:05 UTC: the cost-stop day is over; move the messages it parked (and only those) back to the queue.
        redrive = _lambda.Function(
            self,
            "Redrive",
            function_name="software-factory-redrive-parked",
            runtime=_lambda.Runtime.PYTHON_3_13,
            handler="redrive.handler",
            code=code,
            timeout=cdk.Duration.minutes(2),
            memory_size=128,
            environment={"DLQ_URL": dlq.queue_url, "QUEUE_URL": queue.queue_url},
            log_group=self._log_group(
                "RedriveLogs", "/aws/lambda/software-factory-redrive-parked"
            ),
        )
        dlq.grant_consume_messages(redrive)
        queue.grant_send_messages(redrive)
        redrive_rule = events.Rule(
            self,
            "RedriveDaily",
            rule_name="software-factory-redrive-parked",
            schedule=events.Schedule.cron(minute="5", hour="0"),
            targets=[targets.LambdaFunction(redrive)],
        )
        cdk.CfnOutput(self, "RedriveRuleArn", value=redrive_rule.rule_arn)

        # Scheduled runs. Each only queues a message; the dispatcher (cost stop included) starts the run,
        # and the queue drains only while factory_dispatch is on.
        self.schedules = []
        for cid, name, schedule, message in [
            (
                "PmDaily",
                "software-factory-pm-daily",
                events.Schedule.cron(minute="0", hour="6"),
                {"role": "product_manager"},
            ),
            # Dry run while FACTORY_DEV_PUBLISH is off; it skips tasks already in flight or already tried.
            (
                "DevEvery2h",
                "software-factory-developer-2h",
                events.Schedule.cron(minute="0", hour="*/2"),
                {"role": "developer"},
            ),
            # Yesterday's summary row in the runs table (no model calls).
            (
                "DigestDaily",
                "software-factory-digest-daily",
                events.Schedule.cron(minute="15", hour="0"),
                {"role": "digest"},
            ),
        ]:
            rule = events.Rule(
                self,
                cid,
                rule_name=name,
                schedule=schedule,
                targets=[
                    targets.SqsQueue(
                        queue,
                        message_group_id=message["role"],
                        message=events.RuleTargetInput.from_object(message),
                    )
                ],
            )
            self.schedules.append(rule)
            cdk.CfnOutput(self, f"{cid}RuleArn", value=rule.rule_arn)

        api = apigw.HttpApi(
            self,
            "Webhook",
            api_name="software-factory-webhook",
            create_default_stage=False,
        )
        api.add_routes(
            path="/github",
            methods=[apigw.HttpMethod.POST],
            integration=integrations.HttpLambdaIntegration(
                "IngressIntegration", ingress
            ),
        )
        access_logs = self._log_group(
            "WebhookAccessLogs", "/aws/apigateway/software-factory-webhook"
        )
        stage = apigw.HttpStage(
            self,
            "WebhookStage",
            http_api=api,
            stage_name="$default",
            auto_deploy=True,
            throttle=apigw.ThrottleSettings(rate_limit=10, burst_limit=20),
        )
        stage.node.default_child.access_log_settings = apigw.CfnStage.AccessLogSettingsProperty(
            destination_arn=access_logs.log_group_arn,
            format='{"requestId":"$context.requestId","ip":"$context.identity.sourceIp","route":"$context.routeKey",'
            '"status":"$context.status","len":"$context.responseLength","time":"$context.requestTime"}',
        )
        return api

    # --- cost + coordinator ------------------------------------------------
    def _budget(self) -> sns.Topic:
        topic = sns.Topic(
            self,
            "BudgetAlerts",
            topic_name="software-factory-budget-alerts",
            enforce_ssl=True,
        )
        topic.add_to_resource_policy(
            iam.PolicyStatement(
                actions=["sns:Publish"],
                resources=[topic.topic_arn],
                principals=[iam.ServicePrincipal("budgets.amazonaws.com")],
                conditions={"StringEquals": {"aws:SourceAccount": self.account}},
            )
        )
        budgets.CfnBudget(
            self,
            "Budget",
            budget=budgets.CfnBudget.BudgetDataProperty(
                budget_name="software-factory",
                budget_type="COST",
                time_unit="MONTHLY",
                budget_limit=budgets.CfnBudget.SpendProperty(amount=150, unit="USD"),
                # shortcut: tag filter only counts tagged resources, and only once the payer activates the
                # Project cost-allocation tag; Bedrock tokens are not tagged. RunCostUSD metric is the real meter.
                cost_filters={"TagKeyValue": ["user:Project$SoftwareFactory"]},
            ),
            notifications_with_subscribers=[
                budgets.CfnBudget.NotificationWithSubscribersProperty(
                    notification=budgets.CfnBudget.NotificationProperty(
                        comparison_operator="GREATER_THAN",
                        notification_type="ACTUAL",
                        threshold=80,
                        threshold_type="PERCENTAGE",
                    ),
                    subscribers=[
                        budgets.CfnBudget.SubscriberProperty(
                            subscription_type="SNS", address=topic.topic_arn
                        )
                    ],
                )
            ],
        )
        return topic

    def _cost_alarms(self, topic: sns.Topic) -> None:
        topic.add_to_resource_policy(
            iam.PolicyStatement(
                actions=["sns:Publish"],
                resources=[topic.topic_arn],
                principals=[iam.ServicePrincipal("cloudwatch.amazonaws.com")],
                conditions={
                    "StringEquals": {"aws:SourceAccount": self.account},
                    "ArnLike": {
                        "aws:SourceArn": f"arn:aws:cloudwatch:{self.region}:{self.account}:alarm:software-factory-*"
                    },
                },
            )
        )
        alarm = cloudwatch.Alarm(
            self,
            "DailyCostAlarm",
            alarm_name="software-factory-daily-run-cost",
            alarm_description="Factory agents' model spend (RunCostUSD) above $5 in one day",
            metric=cloudwatch.Metric(
                namespace=METRIC_NAMESPACE,
                metric_name="RunCostUSD",
                statistic="Sum",
                period=cdk.Duration.days(1),
            ),
            threshold=5,
            evaluation_periods=1,
            comparison_operator=cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
            treat_missing_data=cloudwatch.TreatMissingData.NOT_BREACHING,
        )
        alarm.add_alarm_action(cw_actions.SnsAction(topic))

    def _readonly_role(
        self, data: SoftwareFactoryDataStack, coordinator_role_name: str
    ) -> None:
        role = iam.Role(
            self,
            "ReadOnly",
            role_name="software-factory-readonly",
            assumed_by=iam.ArnPrincipal(
                f"arn:aws:iam::{self.account}:role/{coordinator_role_name}"
            ),
            description="Kiro Crew coordinator: read factory runs and metrics",
        )
        role.add_to_policy(
            iam.PolicyStatement(
                actions=[
                    "dynamodb:GetItem",
                    "dynamodb:Query",
                    "dynamodb:DescribeTable",
                ],
                resources=[data.runs.table_arn],
            )
        )
        # Metric reads accept no resource ARN.
        role.add_to_policy(
            iam.PolicyStatement(
                actions=["cloudwatch:GetMetricData", "cloudwatch:ListMetrics"],
                resources=["*"],
            )
        )
        role.add_to_policy(
            iam.PolicyStatement(
                actions=["logs:StartQuery", "logs:FilterLogEvents"],
                resources=[
                    f"arn:aws:logs:{self.region}:{self.account}:log-group:/aws/bedrock-agentcore/runtimes/software_factory*",
                    f"arn:aws:logs:{self.region}:{self.account}:log-group:/aws/lambda/software-factory-*",
                ],
            )
        )
        role.add_to_policy(
            iam.PolicyStatement(actions=["logs:GetQueryResults"], resources=["*"])
        )
